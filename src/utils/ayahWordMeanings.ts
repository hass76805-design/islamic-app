/** Remove UTF BOM and unwanted invisible markers from Quranic verse strings */
export function cleanQuranText(text: string): string {
  return text.replace(/[\uFEFF\u200B-\u200D\u2060]/g, '').trim();
}

/** Clean weird curly braces or stray formatting artifacts in Tafsir strings */
export function cleanTafsirText(text: string): string {
  return text
    .replace(/[\uFEFF\u200B-\u200D]/g, '')
    .replace(/\{/g, '«')
    .replace(/\}/g, '»')
    .replace(/\s+/g, ' ')
    .trim();
}

function stripDiacritics(text: string): string {
  return text
    .replace(/[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED]/g, '')
    .replace(/[\u0640\uFEFF]/g, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .trim();
}

