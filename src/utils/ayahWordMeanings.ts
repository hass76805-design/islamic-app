/**
 * Extract rich, readable word meanings ("معاني الكلمات") for a specific Ayah by
 * 1) parsing glosses directly inside its Al-Muyassar Tafsir, and
 * 2) enriching with verified vocabulary matches for words appearing in the Ayah.
 */
export function extractAyahWordMeanings(
  ayahText: string,
  tafsirText?: string,
): WordMeaningItem[] {
  const results: WordMeaningItem[] = [];
  const seenNorm = new Set<string>();

  const cleanedAyah = cleanQuranText(ayahText);
  const cleanedTafsir = tafsirText ? cleanTafsirText(tafsirText) : '';

  // 1. Parse parenthetical / inline glosses from Tafsir text
  if (cleanedTafsir) {
    // Pattern: (الكلمة) أي ... أو : ...
    const parenRegex = /\(([^()]{2,30})\)\s*([^.،؛()]{4,80})/g;
    let m: RegExpExecArray | null;
    while ((m = parenRegex.exec(cleanedTafsir)) !== null) {
      const word = m[1].trim();
      let meaning = m[2].trim();
      meaning = meaning.replace(/^(أي:|أي|يعني:|يعني|:|-)\s*/u, '').trim();
      const norm = stripDiacritics(word);
      if (
        norm.length >= 2 &&
        meaning.length >= 4 &&
        !seenNorm.has(norm) &&
        word.split(/\s+/).length <= 3
      ) {
        seenNorm.add(norm);
        results.push({word, meaning});
      }
      if (results.length >= 6) break;
    }

    // Pattern: «word» أي: meaning
    const ayRegex = /([^\s،.]{2,22})\s+أي:\s*([^.،؛]{4,80})/g;
    while (results.length < 6 && (m = ayRegex.exec(cleanedTafsir)) !== null) {
      const word = m[1].replace(/[«»()]/g, '').trim();
      const meaning = m[2].trim();
      const norm = stripDiacritics(word);
      if (norm.length >= 2 && meaning.length >= 4 && !seenNorm.has(norm)) {
        seenNorm.add(norm);
        results.push({word, meaning});
      }
    }
  }

  // 2. Match verse tokens against curated Quranic dictionary
  const rawTokens = cleanedAyah
    .replace(/[﴿﴾().,،؛؟!]/g, ' ')
    .split(/\s+/)
    .filter(Boolean);

  for (const tok of rawTokens) {
    const norm = stripDiacritics(tok);
    if (!norm || norm.length < 2 || EXTRA_STOP_WORDS.has(norm)) continue;

    // Exact match or stripped common conjunction prefix (و / ف / ب / ل / ك)
    let meaning = QURAN_VOCAB_DICT[norm];
    let displayWord = tok;

    if (!meaning && norm.length > 3 && /^[وفبلك]/.test(norm)) {
      const withoutPrefix = norm.slice(1);
      if (QURAN_VOCAB_DICT[withoutPrefix]) {
        meaning = QURAN_VOCAB_DICT[withoutPrefix];
      } else if (norm.startsWith('ال') === false && withoutPrefix.startsWith('ال')) {
        meaning = QURAN_VOCAB_DICT[withoutPrefix];
      }
    }

    // Also try removing 'ال' prefix if present
    if (!meaning && norm.startsWith('ال') && norm.length > 4) {
      const bare = norm.slice(2);
      if (QURAN_VOCAB_DICT[bare]) {
        meaning = QURAN_VOCAB_DICT[bare];
      }
    }

    if (meaning && !seenNorm.has(norm)) {
      seenNorm.add(norm);
      results.push({word: displayWord, meaning});
    }
    if (results.length >= 8) break;
  }

  // 3. Fallback: split clean Tafsir clauses for uncommon words if still sparse
  if (results.length === 0 && cleanedTafsir) {
    const clauses = cleanedTafsir
      .split(/[،؛.]/)
      .map((s) => s.trim())
      .filter((s) => s.length >= 8);
    if (clauses.length > 0) {
      results.push({
        word: rawTokens.slice(0, 3).join(' ') || 'معنى الآية',
        meaning: clauses[0],
      });
      if (clauses[1]) {
        results.push({
          word: rawTokens.slice(3, 6).join(' ') || 'بيان إضافي',
          meaning: clauses[1],
        });
      }
    }
  }

  return results;
}
