function normalizeArSpeech(text: string): string {
  return text
    .replace(/[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\uFEFF]/g, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .trim();
}

export function matchRafiqiWordFromSpeech(inputText: string): RafiqiWordEntry {
  const norm = normalizeArSpeech(inputText);
  if (!norm) return RAFIQI_WORDS_30[4]; // السكينة

  for (const entry of RAFIQI_WORDS_30) {
    if (norm.includes(normalizeArSpeech(entry.wordAr))) {
      return entry;
    }
    for (const kw of entry.keywords) {
      if (norm.includes(normalizeArSpeech(kw))) {
        return entry;
      }
    }
  }

  // Fallback friendly reassurance
  return RAFIQI_WORDS_30[0]; // الصبر
}
